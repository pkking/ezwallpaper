"""Unit tests for deterministic Sway E2E fixture generation and frame assertions."""
from __future__ import annotations

import importlib.util
from pathlib import Path
import struct
import unittest
import zlib

MODULE = Path(__file__).resolve().parents[1] / "tests" / "e2e" / "sway" / "run.py"
spec = importlib.util.spec_from_file_location("sway_headless_e2e", MODULE)
assert spec and spec.loader
harness = importlib.util.module_from_spec(spec)
spec.loader.exec_module(harness)


def ppm(width: int, height: int, rgb: tuple[int, int, int]) -> bytes:
    return f"P6\n{width} {height}\n255\n".encode() + bytes(rgb) * (width * height)


class SwayE2EHelpers(unittest.TestCase):
    def test_png_valid_signature_chunk_checksums_and_pixel_stream(self):
        image = harness.solid_png(3, 2, (232, 36, 42))
        self.assertTrue(image.startswith(b"\x89PNG\r\n\x1a\n"))
        pos = 8
        chunks = {}
        while pos < len(image):
            size = struct.unpack("!I", image[pos : pos + 4])[0]
            tag = image[pos + 4 : pos + 8]
            data = image[pos + 8 : pos + 8 + size]
            crc = struct.unpack("!I", image[pos + 8 + size : pos + 12 + size])[0]
            self.assertEqual(crc, zlib.crc32(tag + data))
            chunks[tag] = data
            pos += 12 + size
        self.assertEqual(pos, len(image))
        self.assertEqual(struct.unpack("!2I", chunks[b"IHDR"][:8]), (3, 2))
        self.assertEqual(zlib.decompress(chunks[b"IDAT"]), (b"\x00" + bytes((232, 36, 42)) * 3) * 2)

    def test_ppm_parsing_and_reject_malformed_payloads(self):
        frame = ppm(harness.WIDTH, harness.HEIGHT, harness.COLORS["red"])
        self.assertEqual(harness.parse_ppm(frame)[:2], (harness.WIDTH, harness.HEIGHT))
        self.assertEqual(harness.color_coverage(frame, harness.COLORS["red"]), 1)
        self.assertEqual(harness.color_coverage(frame, harness.COLORS["blue"]), 0)
        for invalid in (b"not a ppm", frame[:-1], frame + b"x", b"P6\n2 3\n1024\n" + b"x" * 18):
            with self.assertRaises(harness.E2EFailure):
                harness.parse_ppm(invalid)

    def test_ppm_comment_and_tolerance(self):
        almost = (230, 39, 40)
        frame = b"P6\n# generated by grim\n320 240\n255\n" + bytes(almost) * (320 * 240)
        self.assertGreaterEqual(harness.color_coverage(frame, harness.COLORS["red"]), 0.99)

    def test_partial_screen_color_does_not_count_as_wallpaper(self):
        red = bytes(harness.COLORS["red"]) * (harness.WIDTH * harness.HEIGHT // 2)
        black = b"\x00" * (harness.WIDTH * harness.HEIGHT * 3 // 2)
        frame = f"P6\n{harness.WIDTH} {harness.HEIGHT}\n255\n".encode() + red + black
        self.assertLess(harness.color_coverage(frame, harness.COLORS["red"]), 0.97)


if __name__ == "__main__":
    unittest.main()
